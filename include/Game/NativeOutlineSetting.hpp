inline bool MatchAob(std::span<const uint8_t> bytes, std::string_view pattern) {
    size_t index = 0;
    for (size_t p = 0; p < pattern.size();) {
        if (pattern[p] == ' ') { ++p; continue; }
        if (p + 1 >= pattern.size() || index >= bytes.size()) return false;
        if (pattern[p] != '?' || pattern[p + 1] != '?') {
            const int hi = Hex(pattern[p]), lo = Hex(pattern[p + 1]);
            if (hi < 0 || lo < 0 || bytes[index] != uint8_t(hi * 16 + lo)) return false;
        }
        ++index; p += 2;
    }
    return index == bytes.size();
}
