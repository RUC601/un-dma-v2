// Returns stable literals for known fixed vocabulary and preserves the caller's
// pointer for every other string. Existing UiText translations should be looked
// up first by the UI.cpp adapter, so there is only one owner for each label.
inline constexpr const char* UiLabel(const char* text, bool chinese) noexcept {
    if (!text)
        return "";
    if (!chinese)
        return text;
    const std::string_view key(text);
    if (key.find("##") != std::string_view::npos)
        return text;
    for (const UiLabelPair& entry : kUiLabels) {
        if (key == entry.en)
            return entry.zh;
    }
    return text;
}

// "All" edits the current runtime values rather than a separate global store.
// Rename only that hero-selection sentinel, never team/bone/scope values.
inline constexpr const char* UiHeroScopeLabel(const char* text, bool chinese) noexcept {
    if (text && std::string_view(text) == "All")
        return UiLabel("Current settings", chinese);
    return UiLabel(text, chinese);
}

