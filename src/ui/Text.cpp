const char* Get(UiText id, bool chinese) {
    const size_t index = static_cast<size_t>(id);
    if (index >= static_cast<size_t>(IM_ARRAYSIZE(kUiText)))
        return "";

    const char* text = chinese
        ? kUiText[index].zh
        : kUiText[index].en;
    return (text && text[0] != '\0') ? text : kUiText[index].en;
}

